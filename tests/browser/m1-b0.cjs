// 中文：B0 浏览器实测只操作虚构检测记录，不涉及真实采购数据。
// English: Real Chromium validation of ephemeral synthetic data only.
"use strict";
const assert=require("node:assert/strict");
const path=require("node:path");
const fs=require("node:fs");
const {pathToFileURL}=require("node:url");
const {chromium}=require("playwright");
(async()=>{
  const html=path.resolve(__dirname,"../../prototype/m1-b0/index.html");
  assert.ok(fs.existsSync(html),"Offline HTML must be generated by build script");
  const browser=await chromium.launch({headless:true});
  const ctx=await browser.newContext();
  const page=await ctx.newPage(),errors=[];
  page.on("pageerror",e=>errors.push(e.message));
  try{
    await page.goto(pathToFileURL(html).href);
    assert.equal(await page.locator("#currentProtocol").innerText(),"file:");
    assert.match(await page.locator("#probeStatus").innerText(),/尚未检测/);
    assert.equal(await page.locator("#checkStorage").isEnabled(),true);
    console.log("PASS M1-B0: standalone file URL loads without a backend");
    await page.locator("#checkStorage").click();
    await page.waitForFunction(()=>document.getElementById("probeStatus").classList.contains("supported")||document.getElementById("probeStatus").classList.contains("failed"),{timeout:12000});
    const first=await page.locator("#probeStatus").innerText();
    assert.match(first,/技术检测通过/);
    assert.match(first,/尚未启用 SRM 自动保存/);
    assert.match(first,/WRITE_REOPEN_READ_DELETE_OK/);
    console.log("PASS M1-B0: synthetic IndexedDB record write/reopen/read/cleanup");

    const databases=await page.evaluate(async()=>typeof indexedDB.databases==="function"?await indexedDB.databases():[]);
    if(databases.length)assert.ok(!databases.some(d=>d.name==="srm-m1-b0-capability"),"Temporary probe database must be deleted");
    console.log("PASS M1-B0: probe does not leave a persistent test database");

    const missing=await page.evaluate(()=>window.M1StorageProbe.check({factory:null}));
    assert.equal(missing.status,"unsupported");
    assert.equal(missing.code,"NO_INDEXEDDB");
    const fake=await page.evaluate(()=>window.M1StorageProbe.check({factory:{open:()=>{throw Error("synthetic disabled")},deleteDatabase:()=>({})}}));
    assert.equal(fake.status,"failed");
    assert.equal(fake.code,"PROBE_FAILED");
    console.log("PASS M1-B0: blocked or absent storage never reports a save");

    await page.reload();
    assert.match(await page.locator("#probeStatus").innerText(),/尚未检测/);
    await page.locator("#checkStorage").click();
    await page.waitForFunction(()=>document.getElementById("probeStatus").classList.contains("supported")||document.getElementById("probeStatus").classList.contains("failed"),{timeout:12000});
    assert.match(await page.locator("#probeStatus").innerText(),/技术检测通过/);
    assert.deepEqual(errors,[]);
    console.log("PASS M1-B0: reopen/reload supports repeated capability check without JavaScript errors");
  } finally {await browser.close()}
})().catch(e=>{console.error(e.stack||e);process.exitCode=1});
